/**
 * Shadow Fight–style weapon kits.
 * Each weapon has light / heavy / special (+ optional light2 chain).
 */

export type MoveDef = {
  id: string;
  name: string;
  startup: number;
  active: number;
  recovery: number;
  damage: number;
  chip: number;
  hitstun: number;
  blockstun: number;
  knockback: number;
  /** Horizontal reach from fighter center toward facing */
  range: number;
  hitboxH: number;
  /** Offset of hitbox center from feet (negative = up) */
  hitboxYOffset: number;
  staminaCost: number;
  /** Forward body slide on startup/active */
  lunge?: number;
  /** Visual / AI hint */
  style: "jab" | "slash" | "thrust" | "spin" | "overhead" | "sweep";
};

export type WeaponDef = {
  id: string;
  name: string;
  title: string;
  blurb: string;
  /** Hex metal / wood color for sprites */
  metal: string;
  grip: string;
  reach: "short" | "mid" | "long";
  light: MoveDef;
  /** Optional chain — press light again during light recovery */
  light2?: MoveDef;
  heavy: MoveDef;
  special: MoveDef;
};

function move(partial: MoveDef): MoveDef {
  return partial;
}

