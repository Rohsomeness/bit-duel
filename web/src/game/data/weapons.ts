export function getWeapon(id: string): WeaponDef {
  const w = WEAPONS.find((x) => x.id === id);
  if (!w) throw new Error(`Unknown weapon: ${id}`);
  return w;
}

export function totalMoveFrames(m: MoveDef): number {
  return m.startup + m.active + m.recovery;
}

/** Rough max threat range for AI spacing */
export function weaponThreatRange(w: WeaponDef): number {
  return Math.max(w.light.range, w.heavy.range, w.special.range, w.light2?.range ?? 0);
}
